def _hash(stem: str, options: list[str]) -> str:
    return hashlib.sha256(json.dumps([stem.strip(), [o.strip() for o in options]]).encode()).hexdigest()


def seed_syllabus(db: Session) -> None:
    chapters = {c.code: c for c in db.scalars(select(SyllabusChapter))}
    for i, (code, subject, cls, name, hours) in enumerate(CHAPTERS):
        if code not in chapters:
            chapters[code] = SyllabusChapter(
                code=code, subject=subject, class_level=cls, name=name, est_hours=hours, sort_order=i,
                source_name=SYLLABUS_SOURCE, source_url=SYLLABUS_URL,
                verification_status=VerificationStatus.pending_review)
            db.add(chapters[code])
    db.commit()


def seed_sample_questions(db: Session) -> None:
    """Original sample questions (demo/dev only; production loads a reviewed bank)."""
    chapters = {c.code: c for c in db.scalars(select(SyllabusChapter))}
    existing = set(db.scalars(select(Question.content_hash)))
    for code, topic, diff, stem, options, correct, expl in QUESTIONS:
        h = _hash(stem, options)
        if h in existing:
            continue
        ch = chapters[code]
        db.add(Question(subject=ch.subject, chapter_id=ch.id, topic=topic, difficulty=diff, stem=stem, options=options,
                        correct_index=correct, explanation=expl, review_status="sample", content_hash=h,
                        source_name="NEET Compass original sample question (not expert-reviewed)",
                        verification_status=VerificationStatus.unverified))
    db.commit()
